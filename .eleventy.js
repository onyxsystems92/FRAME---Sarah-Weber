const yaml = require("js-yaml");

module.exports = function (eleventyConfig) {
  // Eleventy 3 has no built-in YAML data support — register it so
  // src/_data/site.yaml (and any future .yaml data/front matter) loads.
  eleventyConfig.addDataExtension("yaml", (contents) => yaml.load(contents));

  // Static passthrough — unchanged design system files and real assets.
  eleventyConfig.addPassthroughCopy("src/assets");
  eleventyConfig.addPassthroughCopy("src/images");
  eleventyConfig.addPassthroughCopy("src/fonts.css");
  eleventyConfig.addPassthroughCopy("src/styles.css");
  eleventyConfig.addPassthroughCopy("src/frame-navigation.css");
  eleventyConfig.addPassthroughCopy("src/aktuelles.css");
  eleventyConfig.addPassthroughCopy("src/script.js");
  eleventyConfig.addPassthroughCopy({ admin: "admin" });

  const notExcluded = (item) => item.data.eleventyExcludeFromCollections !== true;

  eleventyConfig.addCollection("team", (api) =>
    api
      .getFilteredByGlob("src/team/*.md")
      .filter(notExcluded)
      .sort((a, b) => (a.data.order ?? 99) - (b.data.order ?? 99))
  );

  eleventyConfig.addCollection("aktuelles", (api) =>
    api.getFilteredByGlob("src/aktuelles/*.md").filter(notExcluded)
  );

  // content/aktuelles.json is generated by src/aktuelles-feed.11ty.js as a
  // normal Eleventy template (permalink-based), so it always resolves to
  // the real output directory instead of a hand-tracked path.

  return {
    dir: {
      input: "src",
      output: "dist",
      includes: "_includes",
      data: "_data",
    },
    templateFormats: ["njk", "md", "11ty.js"],
    htmlTemplateEngine: "njk",
    markdownTemplateEngine: "njk",
  };
};
